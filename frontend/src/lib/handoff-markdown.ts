import type { HandoffReport } from "@/lib/types";

function bullet(items: string[]): string {
  return items.length ? items.map((item) => `- ${item}`).join("\n") : "- None recorded.";
}

export function handoffToMarkdown(report: HandoffReport): string {
  const decisions = report.human_decisions.length
    ? report.human_decisions.map((review) => [
      `### ${review.decision.replaceAll("_", " ")} — ${review.timestamp}`,
      `- Reviewer label: \`${review.reviewer_identifier}\` (unverified local-development identity)`,
      `- Justification: ${review.justification}`,
      `- Proposal version: ${review.proposal_version}; source SHA-256: \`${review.source_sha256}\`; diff SHA-256: \`${review.diff_sha256}\``,
      "- Outstanding questions:",
      ...(review.outstanding_questions.length ? review.outstanding_questions.map((question) => `  - ${question}`) : ["  - None recorded."]),
    ].join("\n")).join("\n\n")
    : "No human decision is recorded.";
  const findings = report.validation_and_risks.static_checks.map((finding) => `- **${finding.check}** (${finding.status}): ${finding.detail}`);
  const plannedSteps = report.task.planned_steps.length
    ? report.task.planned_steps.map((step, index) => `${index + 1}. ${step.replace(/^\d+\.\s*/, "")}`)
    : ["No planned steps recorded."];
  const plannedValidation = bullet(report.task.planned_validation_requirements);
  return [
    `# Engineering Handoff: ${report.task.objective}`,
    "",
    `- Repository: \`${report.repository_id}\``,
    `- Task: \`${report.task.task_id}\``,
    `- Generated: ${report.generated_at}`,
    `- Proposal lifecycle: **${report.task.proposal_lifecycle_state}** (version ${report.task.proposal_version})`,
    `- Provider: **${report.provider}**${report.is_mock ? " (mock output)" : ""}`,
    `- Planning provider: **${report.task.planning_provider}**`,
    "",
    "## Project and task context",
    "",
    `- Progress: ${report.task.current_progress}`,
    `- Relevant files: ${report.task.relevant_files.map((path) => `\`${path}\``).join(", ") || "None"}`,
    `- Source references: ${report.task.source_references.map((ref) => `\`${ref.path}:${ref.line}\``).join(", ") || "None"}`,
    "### Planned implementation steps",
    "",
    ...plannedSteps,
    "",
    "### Planned validation",
    "",
    plannedValidation,
    "",
    "## Technical understanding — verified static analysis",
    "",
    ...report.technical_understanding.verified_context.map((item) => `- ${item}`),
    `- Relevant modules: ${report.technical_understanding.relevant_modules.map((module) => `\`${module.name}\` (${module.path})`).join(", ") || "None found"}`,
    `- Functions: ${report.technical_understanding.relevant_functions.join(", ") || "None found"}`,
    `- Classes: ${report.technical_understanding.relevant_classes.join(", ") || "None found"}`,
    `- Imports: ${report.technical_understanding.relevant_imports.join("; ") || "None found"}`,
    `- Dependency manifests: ${report.technical_understanding.dependency_manifests.join("; ") || "None found"}`,
    "",
    "## Proposed change — mock generated, not applied",
    "",
    report.proposed_change.summary,
    `- Proposal generator: **deterministic allowlist**; transformation: \`${report.proposed_change.transformation_id}\``,
    `- Originating plan provider: **${report.proposed_change.originating_plan_provider}**`,
    `- Target: ${report.proposed_change.target_files.map((target) => `\`${target.path}\` (source SHA-256 \`${target.original_sha256}\`)`).join(", ")}`,
    `- Diff SHA-256: \`${report.proposed_change.diff_sha256}\``,
    `- Source revision: **${report.proposed_change.source_revision_status}**`,
    "",
    "## Human decisions — local, unverified identities",
    "",
    decisions,
    "",
    "## Validation and risks",
    "",
    "### Static checks",
    "",
    ...(findings.length ? findings : ["- None recorded."]),
    "",
    "### Runtime validation",
    "",
    `- Status: **${report.validation_and_risks.runtime_tests_status}**`,
    `- Detail: ${report.validation_and_risks.runtime_tests_reason}`,
    "",
    "### Risks",
    "",
    bullet(report.validation_and_risks.risks),
    "",
    "### Assumptions",
    "",
    bullet(report.validation_and_risks.assumptions),
    "",
    "### Dependencies and evidence gaps",
    "",
    "**Unresolved dependencies**",
    "",
    bullet(report.validation_and_risks.unresolved_dependencies),
    "",
    "**Missing or unsupported evidence**",
    "",
    bullet(report.validation_and_risks.unsupported_evidence),
    "",
    "## Isolated runtime validation",
    "",
    `- Status: **${report.runtime_execution.status}**`,
    `- Sandbox: ${report.runtime_execution.sandbox_summary}`,
    `- Evidence ID: ${report.runtime_execution.evidence_id ? `\`${report.runtime_execution.evidence_id}\`` : "None recorded"}`,
    `- Test case: \`${report.runtime_execution.test_case}\`; command ID: \`${report.runtime_execution.test_command_id}\``,
    `- Exit code: ${report.runtime_execution.exit_code ?? "not run"}; duration: ${report.runtime_execution.duration_ms === null ? "not run" : `${report.runtime_execution.duration_ms} ms`}`,
    `- Source SHA-256: \`${report.runtime_execution.source_sha256}\`; diff SHA-256: \`${report.runtime_execution.diff_sha256}\``,
    "- Test results:",
    ...(report.runtime_execution.test_results.length ? report.runtime_execution.test_results.map((item) => `  - ${item}`) : ["  - None recorded." ]),
    "- Remaining work:",
    ...(report.runtime_execution.remaining_work.length ? report.runtime_execution.remaining_work.map((item) => `  - ${item}`) : ["  - None recorded." ]),
    "- The original repository was not modified; any future execution must remain in the disposable sandbox.",
    "",
    "## Next engineer actions",
    "",
    ...report.next_engineer_actions.map((action) => `- ${action.action}${action.required_approval ? " (further approval required)" : ""} — ${action.status}`),
    "",
    `> ${report.provenance_note}`,
    "",
  ].join("\n");
}
